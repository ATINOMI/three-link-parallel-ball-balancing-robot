/**
  * @brief  Update the key state with debounce logic.
  * @param  key: Pointer to the KeyDebounce_t structure.
  * @param  raw: The raw GPIO pin state (GPIO_PIN_SET or GPIO_PIN_RESET).
  * @retval 1 if the key is considered pressed (stable low), 0 otherwise.
  */
static uint8_t key_update(KeyDebounce_t *key, GPIO_PinState raw)
{
  if (raw == key->stable_state)
  {
    key->count = 0U;
    return 0U;
  }

  if (++key->count >= KEY_DEBOUNCE_SAMPLES)
  {
    key->count = 0U;
    key->stable_state = raw;
    return raw == GPIO_PIN_RESET;
  }

  return 0U;
}
